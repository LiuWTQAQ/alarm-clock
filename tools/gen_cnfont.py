# Generate 1-bit Microsoft YaHei bitmap font header for TFT_eSPI
from PIL import Image, ImageDraw, ImageFont
import sys

FONT = "/System/Library/Fonts/STHeiti Medium.ttc"

CHARS = ("0123456789:°C-. "
         "周五一二三四六日"
         "月"
         "晴多云雨阴"
         "下个闹钟"
         "至"
         "单击停止长按懒睡双夜灯"
         "已开连接剩余内存"
         "度天气城市更新失败获取中无数据网络"
         "北京上海广州深圳杭州成都武汉西安南京重庆天津苏州长沙青岛大连厦门"
         "合肥福州昆明南昌贵阳太原石家庄哈尔滨长春沈阳郑州济南南宁海口三亚"
         "兰州银川西宁乌鲁木齐呼和浩特拉萨香港澳门台北"
         "雾雷阵雪暴冰雹冻毛转"
         "优良轻中重严空气沙尘霾")

def build(size):
    font = ImageFont.truetype(FONT, size, index=0)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in dict.fromkeys(CHARS):
        if ch == " ":
            glyphs.append((ord(ch), 0, 0, 0, 0, max(1, int(round(font.getlength(" ")))), b""))
            continue
        pad = size
        img = Image.new("L", (size * 3, size * 3), 0)
        d = ImageDraw.Draw(img)
        d.text((pad, pad), ch, font=font, fill=255)
        box = img.getbbox()
        if box is None:
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        w, h = crop.size
        # pack 1-bit, row-major, rows padded to full bytes
        row_bytes = (w + 7) // 8
        data = bytearray()
        px = crop.load()
        for y in range(h):
            row = bytearray(row_bytes)
            for x in range(w):
                if px[x, y] > 110:          # threshold, keeps strokes solid
                    row[x >> 3] |= (0x80 >> (x & 7))
            data += row
        adv = int(round(font.getlength(ch)))
        glyphs.append((ord(ch), w, h, x0 - pad, y0 - pad, adv, bytes(data)))
    return ascent, descent, glyphs

def emit(name, size, ascent, glyphs, out):
    out.append(f"// {name}: Microsoft YaHei {size}px, {len(glyphs)} glyphs, ascent {ascent}")
    out.append(f"static const uint8_t {name}_data[] = {{")
    blob = bytearray()
    offsets = []
    for g in glyphs:
        offsets.append(len(blob))
        blob += g[6]
    for i in range(0, len(blob), 16):
        out.append("  " + ",".join(f"0x{b:02X}" for b in blob[i:i+16]) + ",")
    out.append("};")
    out.append(f"static const CnGlyph {name}_glyphs[] = {{")
    for (cp, w, h, xo, yo, adv, _), off in zip(glyphs, offsets):
        out.append(f"  {{0x{cp:04X},{w},{h},{xo},{yo},{adv},{off}}},")
    out.append("};")
    out.append(f"static const CnFont {name} = {{ {name}_glyphs, {len(glyphs)}, {ascent}, {name}_data }};")
    out.append("")

def main():
    sizes = [28, 18, 15]
    heads = []
    for s in sizes:
        ascent, descent, glyphs = build(s)
        emit(f"cn{s}", s, ascent, glyphs, heads)
        # report widths of the strings we will draw
        f = ImageFont.truetype(FONT, s, index=0)
        for txt in ["周五 10月23日", "下一个闹钟", "周一至周五", "单击停止  长按懒睡  双击夜灯", "多云", "24°C", "剩余 363 KB", "闹钟已开"]:
            print(f"  size {s:>2}  {txt!r:34s} width={f.getlength(txt):6.1f}  h={ascent}+{descent}", file=sys.stderr)
    body = """// Auto-generated by gen_cnfont.py -- Microsoft YaHei bitmap glyphs (1 bit/px)
// Copy to firmware/include/ui_font_cn.h ; add nothing to platformio.ini.
#pragma once
#include <stdint.h>

struct CnGlyph { uint32_t cp; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint16_t off; };
struct CnFont  { const CnGlyph* g; uint16_t n; uint8_t ascent; const uint8_t* data; };

"""
    body += "\n".join(heads)
    with open("/Users/liuwentao/Documents/deepseek-harness/default-workspace/ui_font_cn.h", "w") as fp:
        fp.write(body)
    print("written ui_font_cn.h", file=sys.stderr)

main()
